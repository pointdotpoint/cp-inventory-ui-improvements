#!/usr/bin/env python3
"""Adds a pose switch to the vanilla preview animation graph (player_paperdoll.animgraph).

Input and output are WolvenKit JSON (`WolvenKit.CLI convert serialize/deserialize`).

The new switch sits between the graph's Output node and everything vanilla produced:
  input 0      -> the untouched vanilla pose
  inputs 1..N  -> one SkAnim per pose name in poses_female.txt
The switch index comes from a float input reading the anim feature "WardrobePose", field
"pose", which the redscript side applies to the preview puppet (AnimFeature_WardrobePose).

Also writes mod/r6/tweaks/PreviewPoses/poses.yaml, which PreviewPosesCatalog reads at runtime.

Usage:
  build_pose_graph.py <in.json> <out.json>   # patch the graph and rewrite poses.yaml
  build_pose_graph.py --catalog-only         # rewrite poses.yaml from poses_female.txt
"""
import copy
import json
import os
import sys

FEATURE_NAME = "WardrobePose"
FEATURE_CLASS = "AnimFeature_WardrobePose"
FEATURE_FIELD = "pose"

POSE_LIST = os.path.join(os.path.dirname(os.path.abspath(__file__)), "poses_female.txt")
POSES_YAML = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "mod", "r6", "tweaks",
                          "PreviewPoses", "poses.yaml")


def pack_comment(text):
    """Pack name started by a comment, or None when the comment is not a pack header.

    `# pack: <name>` keeps the rest of the line, spaces included.
    `# <word>` still starts a pack when the word has no spaces.
    """
    if text.lower().startswith("pack:"):
        name = text[5:].strip()
        if not name:
            raise SystemExit("empty pack name")
        return name
    if text and " " not in text:
        if not text.replace("_", "").isalnum():
            raise SystemExit(f"pack name {text!r} is not a plain word")
        return text
    return None


def load_pose_file():
    """Pose names in selector order, and the pack of each one.

    Script pose 0 is the vanilla pose and is not in this list; script indices 1..N
    follow the returned names, which is also the order of the switch inputs.
    """
    poses = []
    pack_of = []
    pack_names = []
    current = None
    with open(POSE_LIST) as f:
        for line_no, raw in enumerate(f, 1):
            line = raw.strip()
            if not line:
                continue
            if line.startswith("#"):
                try:
                    name = pack_comment(line[1:].strip())
                except SystemExit as exc:
                    raise SystemExit(f"{POSE_LIST}:{line_no}: {exc}")
                if name is None:
                    continue
                if name not in pack_names:
                    pack_names.append(name)
                current = pack_names.index(name)
                continue
            if current is None:
                raise SystemExit(f"{POSE_LIST}:{line_no}: {line} is not under a pose pack")
            poses.append(line)
            pack_of.append(current)
    if not poses:
        raise SystemExit(f"{POSE_LIST}: no poses")
    return poses, pack_of, pack_names


def yaml_string(value):
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def write_catalog(poses, pack_of, pack_names):
    """Writes the tweak table the game loads. One entry per clip, in switch order."""
    if len(poses) != len(pack_of):
        raise SystemExit("pose list and pack list differ in length")
    for pack in pack_of:
        if pack < 0 or pack >= len(pack_names):
            raise SystemExit(f"pack index {pack} is outside {len(pack_names)} packs")
    lines = [
        "# Generated by tools/build_pose_graph.py from tools/poses_female.txt. Do not edit.",
        "# Index i is paperdoll switch input i+1. Pose 0 is the vanilla preview pose and is not listed.",
        "PreviewPoses.list.animations:",
    ]
    for name in poses:
        lines.append(f"  - {yaml_string(name)}")
    lines.append("PreviewPoses.list.packNames:")
    for pack in pack_of:
        lines.append(f"  - {yaml_string(pack_names[pack])}")
    lines.append("PreviewPoses.list.packs:")
    for pack in pack_of:
        lines.append(f"  - {yaml_string(str(pack))}")
    lines.append("")
    os.makedirs(os.path.dirname(POSES_YAML), exist_ok=True)
    with open(POSES_YAML, "w") as f:
        f.write("\n".join(lines))


def cname(value):
    return {"$type": "CName", "$storage": "string", "$value": value}


def walk(obj, fn):
    if isinstance(obj, dict):
        fn(obj)
        for value in obj.values():
            walk(value, fn)
    elif isinstance(obj, list):
        for value in obj:
            walk(value, fn)


def main(src, dst):
    doc = json.load(open(src))
    root = doc["Data"]["RootChunk"]

    handles = {}
    templates = {}

    def collect(o):
        if "HandleId" in o:
            handles[int(o["HandleId"])] = o["Data"]
        t = o.get("$type")
        if t in ("animAnimNode_Switch", "animAnimNode_SkAnim", "animAnimNode_FloatInput") and t not in templates:
            templates[t] = o

    walk(root, collect)
    next_id = max(handles) + 1

    def new_handle(data):
        nonlocal next_id
        handle = {"HandleId": str(next_id), "Data": data}
        next_id += 1
        return handle

    def fresh(node_type):
        node = copy.deepcopy(templates[node_type])
        found = []
        walk(node, lambda o: found.append(o) if "HandleId" in o or "HandleRefId" in o else None)
        if node_type != "animAnimNode_Switch" and found:
            raise SystemExit(f"template {node_type} contains handles; pick another template")
        return node

    output = handles[1]
    if output.get("$type") != "animAnimNode_Output":
        raise SystemExit(f"handle 1 is {output.get('$type')}, expected the Output node")
    vanilla_link = output["node"]

    selector = fresh("animAnimNode_FloatInput")
    selector["group"] = cname(FEATURE_NAME)
    selector["name"] = cname(FEATURE_FIELD)
    selector_handle = new_handle(selector)

    inputs = [vanilla_link]
    poses, pack_of, pack_names = load_pose_file()
    new_nodes = [selector_handle]
    for pose in poses:
        anim = fresh("animAnimNode_SkAnim")
        anim["animation"] = cname(pose)
        anim["isLooped"] = 1
        anim["applyMotion"] = 0
        handle = new_handle(anim)
        new_nodes.append(handle)
        inputs.append({"$type": "animPoseLink", "node": handle})

    switch = {key: copy.deepcopy(value) for key, value in templates["animAnimNode_Switch"].items()
              if key not in ("inputNodes", "weightNode", "visMask")}
    switch["inputNodes"] = inputs
    switch["numInputs"] = len(inputs)
    switch["weightNode"] = {"$type": "animFloatLink", "node": selector_handle}
    switch["blendTime"] = 0.2
    switch["visMask"] = []
    switch_handle = new_handle(switch)
    new_nodes.append(switch_handle)

    output["node"] = {"$type": "animPoseLink", "node": switch_handle}

    for handle in new_nodes:
        root["nodesToInit"].append({"HandleRefId": handle["HandleId"]})

    root["animFeatures"].append({
        "$type": "animAnimFeatureEntry",
        "className": cname(FEATURE_CLASS),
        "debugEnabled": 0,
        "forceAllocate": 0,
        "name": cname(FEATURE_NAME),
    })

    json.dump(doc, open(dst, "w"), indent=1)
    write_catalog(poses, pack_of, pack_names)
    print(f"added switch with {len(poses)} poses; handles {new_nodes[0]['HandleId']}..{switch_handle['HandleId']}")


if __name__ == "__main__":
    if len(sys.argv) == 2 and sys.argv[1] == "--catalog-only":
        poses, pack_of, pack_names = load_pose_file()
        write_catalog(poses, pack_of, pack_names)
        print(f"poses.yaml: {len(poses)} poses, {len(pack_names)} packs")
    else:
        main(sys.argv[1], sys.argv[2])
