#!/usr/bin/env python3
"""Generates mod/r6/scripts/WardrobeTabs/WardrobeTabsLocalizationTexts.reds, the mod's shipped
texts, from localization/<lang>.yaml. WardrobeTabsLocalization.reds (the Codeware provider) uses it.

Each YAML file is a list of TweakXL flats, the same format players use for override files:
    WUI_Loc.<lang>.<Name>: "text"
so a translator's override file can be copied into localization/ as it is. en-us.yaml lists
every name; other languages hold any subset (missing names show English). Text may hold
{0}, {1}... (filled by WardrobeTabsTextF); a translation must use the same ones as English. A
language without its own file can borrow another's (ALIASES). The comment at the top of
WardrobeTabsLocalization.reds explains to players how to override any text with their own file.

  python3 tools/gen_localization.py           write the .reds
  python3 tools/gen_localization.py --check   exit 1 if the .reds is out of date
"""
import os
import re
import sys

import yaml

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "localization")
OUT = os.path.join(ROOT, "mod", "r6", "scripts", "WardrobeTabs", "WardrobeTabsLocalizationTexts.reds")
FLAT = "WUI_Loc"
KEY = "WUI-"
ENGLISH = "en-us"
# Codeware's language codes (src/App/Localization/Language.cpp). db-db is the debug language.
LANGS = ["ar-ar", "cz-cz", "db-db", "de-de", "en-us", "es-es", "es-mx", "fr-fr", "hu-hu", "it-it",
         "jp-jp", "kr-kr", "pl-pl", "pt-br", "ru-ru", "th-th", "tr-tr", "ua-ua", "zh-cn", "zh-tw"]
# A language without its own file uses another's texts.
ALIASES = {"es-mx": "es-es"}
# Letters, digits and underscores joined by hyphens.
NAME = re.compile(r"^[A-Za-z0-9_]+(-[A-Za-z0-9_]+)*$")
LINE_KEY = re.compile(r"^([^\s#][^:]*):")
PLACEHOLDER = re.compile(r"\{\d+\}")


class LocError(Exception):
    pass


def parse(path, lang):
    """The file's (name, text) pairs, in file order."""
    with open(path, encoding="utf-8") as f:
        raw = f.read()
    if "\t" in raw:
        raise LocError(f"{path}: contains tabs")
    seen = set()
    for number, line in enumerate(raw.splitlines(), 1):
        match = LINE_KEY.match(line)
        if match:
            key = match.group(1).strip().strip("'\"")
            if key in seen:
                raise LocError(f"{path}:{number}: duplicate {key}")
            seen.add(key)
    data = yaml.safe_load(raw) or {}
    if not isinstance(data, dict):
        raise LocError(f"{path}: not a list of '{FLAT}.{lang}.<Name>: \"text\"' lines")
    prefix = f"{FLAT}.{lang}."
    pairs = []
    for key, text in data.items():
        if not isinstance(key, str) or not key.startswith(prefix):
            raise LocError(f"{path}: {key!r} doesn't start with {prefix}")
        name = key[len(prefix):]
        if not NAME.match(name):
            raise LocError(f"{path}: {name!r}: names are letters, digits and underscores joined by hyphens")
        if not isinstance(text, str):
            raise LocError(f"{path}: {key} isn't a quoted string")
        pairs.append((name, text))
    return pairs


def load_all(src_dir):
    """{lang: [(name, text)]} for every <lang>.yaml, checked against English."""
    langs = {}
    for fname in sorted(os.listdir(src_dir)):
        if not fname.endswith(".yaml"):
            continue
        lang = fname[:-len(".yaml")]
        if lang not in LANGS:
            raise LocError(f"{fname}: {lang} isn't a game language ({' '.join(LANGS)})")
        langs[lang] = parse(os.path.join(src_dir, fname), lang)
    if ENGLISH not in langs:
        raise LocError(f"{src_dir}: no {ENGLISH}.yaml")
    english = dict(langs[ENGLISH])
    for lang, pairs in langs.items():
        for name, text in pairs:
            if name not in english:
                raise LocError(f"{lang}.yaml: {name} isn't in {ENGLISH}.yaml")
            if sorted(PLACEHOLDER.findall(text)) != sorted(PLACEHOLDER.findall(english[name])):
                raise LocError(f"{lang}.yaml: {name}: placeholders differ from English")
    return langs


def redscript_string(text):
    escaped = (text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
               .replace("\t", "\\t").replace("\r", "\\r"))
    return f'"{escaped}"'


def define_func(lang):
    return "Define" + "".join(part.capitalize() for part in lang.split("-"))


def generate(langs):
    lines = [
        "// Generated by tools/gen_localization.py from localization/*.yaml. Don't edit by hand.",
        "//",
        "// The mod's own texts: every name with its English (DefineEnUs), then each shipped translation.",
        "// To translate the mod or change a text, don't edit this file (an update replaces it): add your",
        "// own TweakXL file instead, as explained at the top of WardrobeTabsLocalization.reds. A line here",
        f"//     this.Text(\"{KEY}<Name>\", \"English text\");",
        "// is changed by a line in your file",
        f"//     {FLAT}.<language>.<Name>: \"your text\"",
        f"// e.g. {FLAT}.de-de.Bar-Revert: \"ZURÜCK\". Keep any {{0}}, {{1}}... in your text.",
        "module EquipmentEx",
        "",
        # @addMethod can't target a class defined in scripts, so the texts are a subclass of
        # WardrobeTabsLocalization.reds' WardrobeTabsLocPackageBase, which calls these.
        "public class WardrobeTabsLocPackage extends WardrobeTabsLocPackageBase {",
        # An instance method: arrays returned by static functions came back empty at runtime here.
        f"    // Every text's name (its key without \"{KEY}\"), in English's order.",
        "    public func Names() -> array<String> {",
        "        let names: array<String> = [",
    ]
    names = [name for name, _ in langs[ENGLISH]]
    for i, name in enumerate(names):
        lines.append(f"            {redscript_string(name)}{',' if i < len(names) - 1 else ''}")
    lines += ["        ];", "        return names;", "    }", ""]
    for lang in sorted(langs, key=lambda l: (l != ENGLISH, l)):
        lines.append(f"    protected func {define_func(lang)}() {{")
        for name, text in langs[lang]:
            lines.append(f"        this.Text({redscript_string(KEY + name)}, {redscript_string(text)});")
        lines += ["    }", ""]
    lines += ["    // A shipped language's texts, put over English (an alias uses its target's).",
              "    protected func DefineShipped(lang: String) {"]
    shipped = {lang: lang for lang in langs if lang != ENGLISH}
    for alias, target in ALIASES.items():
        if target in langs and alias not in langs:
            shipped[alias] = target
    for lang in sorted(shipped):
        lines += [f"        if Equals(lang, {redscript_string(lang)}) {{",
                  f"            this.{define_func(shipped[lang])}();", "        }"]
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def main():
    try:
        out = generate(load_all(SRC))
    except LocError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    if "--check" in sys.argv[1:]:
        try:
            with open(OUT, encoding="utf-8") as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current != out:
            print(f"{OUT} is out of date: run python3 tools/gen_localization.py", file=sys.stderr)
            return 1
        print("WardrobeTabsLocalizationTexts.reds up to date")
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
